def P(text='', indent=True, align=None, size=12, bold=False, cn=CN, space_after=0, style='Normal'):
    p = doc.add_paragraph(style=style)
    if not indent:
        p.paragraph_format.first_line_indent = Pt(0)
    if align is not None:
        p.paragraph_format.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if text:
        r = p.add_run(text)
        run_font(r, cn=cn, size=size, bold=bold)
    return p


def H(text, lvl):
    p = doc.add_heading(text, level=lvl)
    for r in p.runs:
        run_font(r, cn=CN_H, size={1: 16, 2: 14, 3: 12}[lvl], bold=True)
    return p


def BULLET(text):
    p = doc.add_paragraph(style='List Bullet')
